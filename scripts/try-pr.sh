#!/usr/bin/env bash
# Run a pull request as its own stack, next to the development stack and without touching it.
# Usage: scripts/try-pr.sh <number> | status | restore
set -euo pipefail

# shellcheck source=scripts/lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

PR_PROJECT="adiutor-pr"
STATE_DIR="$CACHE_DIR/try-pr"
STATE_FILE="$STATE_DIR/state.env"
ENV_FILE="$STATE_DIR/pr.env"
# The invented owner's username, password and TOTP secret, written by the seed (0600). Never in pr.env, which
# the container reads.
OWNER_FILE="$STATE_DIR/owner.env"
COMPOSE_FILE="$STATE_DIR/compose.yml"
PROXY_CONF="$STATE_DIR/proxy.conf"
DATA_DIR="$STATE_DIR/postgres"
WORKTREE="$STATE_DIR/worktree"
DEFAULT_PORT=8091
# The pull request is served on a host name of its own. Browsers scope cookies by host, not by port, so the
# development stack's session on 127.0.0.1 never goes to this name; names under .localhost reach this machine
# (RFC 6761). Only the proxy publishes a port, and it passes the pull request's server only requests for this
# name: a redirect from the pull request to 127.0.0.1:<port> ends at the proxy, with the cookies of 127.0.0.1.
PR_HOST="pr.localhost"
PROXY_IMAGE="nginx:1.30.6-alpine"
# Filled from STATE_FILE by load_state.
PR="" COMMIT="" REF="" PORT="" IMAGE=""

usage() {
  cat <<EOF
Usage: scripts/try-pr.sh <command>

  <number>  Build the pull request's head in a disposable worktree as adiutor:pr-<number> and run it as
            the Compose project $PR_PROJECT with its own disposable PostgreSQL, generated tokens and
            invented fixtures and an owner with a generated password and TOTP secret, on
            http://$PR_HOST:\${ADIUTOR_PR_PORT:-$DEFAULT_PORT}. Telegram is off.
  status    Show the pull request that runs, its health and where its tokens and sign-in are.
  restore   Remove the pull request stack, its database, image, tokens, sign-in and worktree.

One pull request at a time. The development stack (adiutor-dev), its data and docker-compose-dev.yml
are never touched; nothing is pushed or merged, and your working tree is never changed.
State: $STATE_DIR
EOF
}

# The address the owner opens.
pr_url() {
  echo "http://$PR_HOST:$PORT"
}

pr_compose() {
  docker compose -p "$PR_PROJECT" --project-directory "$STATE_DIR" -f "$COMPOSE_FILE" "$@"
}

load_state() {
  [ -f "$STATE_FILE" ] || die "no pull request is running. Start one with: scripts/try-pr.sh <number>"
  # shellcheck source=/dev/null
  source "$STATE_FILE"
}

save_state() {
  {
    echo "PR=$PR"
    echo "COMMIT=$COMMIT"
    echo "REF=$REF"
    echo "PORT=$PORT"
    echo "IMAGE=$IMAGE"
  } >"$STATE_FILE"
}

write_env() {
  local password
  password="$(random_hex)"
  (
    umask 077
    cat >"$ENV_FILE" <<EOF
# Pull request #$PR stack only. Generated by scripts/try-pr.sh; removed by restore. Never commit.
# Telegram is off: no bot settings are set, so this stack can never consume the real bot's updates.
POSTGRES_USER=adiutor
POSTGRES_PASSWORD=$password
POSTGRES_DB=adiutor
DATABASE_URL=postgres://adiutor:$password@postgres:5432/adiutor
ADIUTOR_AUTH_SECRETS=1:$(random_hex)
ADIUTOR_SETTINGS_KEYS=1:$(random_hex)
ADIUTOR_PUBLIC_URL=$(pr_url)
EOF
  )
  chmod 600 "$ENV_FILE"
}

# An older pr.env lacks the keys the server now requires: they are added. Its old token lines stay; the server
# only warns about them.
ensure_auth_secret() {
  [ -f "$ENV_FILE" ] || return 0
  local name
  for name in ADIUTOR_AUTH_SECRETS ADIUTOR_SETTINGS_KEYS; do
    grep -q "^$name=" "$ENV_FILE" && continue
    info "Adding $name to $ENV_FILE"
    (
      umask 077
      echo "$name=1:$(random_hex)" >>"$ENV_FILE"
    )
  done
  chmod 600 "$ENV_FILE"
}

write_compose() {
  cat >"$COMPOSE_FILE" <<EOF
# Pull request #$PR stack. Generated by scripts/try-pr.sh; removed by restore.
services:
  adiutor:
    image: $IMAGE
    env_file: pr.env
    depends_on:
      postgres:
        condition: service_healthy
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL

  # The only published port. It passes on requests for $PR_HOST alone (proxy.conf).
  proxy:
    image: $PROXY_IMAGE
    entrypoint: ["nginx", "-c", "/etc/adiutor-pr/proxy.conf", "-g", "daemon off;"]
    user: "101:101"
    volumes:
      - ./proxy.conf:/etc/adiutor-pr/proxy.conf:ro
    depends_on:
      adiutor:
        condition: service_healthy
    ports:
      - "127.0.0.1:$PORT:8080"
    healthcheck:
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "--header", "Host: $PR_HOST", "http://127.0.0.1:8080/healthz"]
      interval: 5s
      timeout: 5s
      retries: 10
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL

  postgres:
    image: $TEST_POSTGRES_IMAGE
    env_file: pr.env
    volumes:
      - ./postgres:$TEST_POSTGRES_DATA
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \"\$\$POSTGRES_USER\" -d \"\$\$POSTGRES_DB\""]
      interval: 5s
      timeout: 5s
      retries: 10
EOF
}

# Requests for any other host get 421 and never reach the pull request's server. The file holds no secret and
# nginx runs as UID 101, so it is readable by all.
write_proxy_conf() {
  cat >"$PROXY_CONF" <<EOF
# Pull request #$PR stack. Generated by scripts/try-pr.sh; removed by restore.
worker_processes 1;
pid /tmp/nginx.pid;
error_log stderr warn;
events { worker_connections 256; }
http {
  access_log off;
  client_body_temp_path /tmp/client_body;
  proxy_temp_path /tmp/proxy;
  fastcgi_temp_path /tmp/fastcgi;
  uwsgi_temp_path /tmp/uwsgi;
  scgi_temp_path /tmp/scgi;
  server {
    listen 8080 default_server;
    return 421;
  }
  server {
    listen 8080;
    server_name $PR_HOST;
    # nginx may pick this server from an absolute request line; the Host header must name it too.
    if (\$http_host !~* "^${PR_HOST//./\\.}(:[0-9]+)?\$") {
      return 421;
    }
    # The server applies its own limits.
    client_max_body_size 0;
    location / {
      proxy_pass http://adiutor:8080;
      proxy_http_version 1.1;
      proxy_set_header Host \$http_host;
      proxy_set_header Connection "";
      proxy_buffering off;
      proxy_read_timeout 1h;
    }
  }
}
EOF
  chmod 644 "$PROXY_CONF"
}

# Prints the pull request's head commit as GitHub reports it, or nothing when gh cannot tell.
gh_head() {
  command -v gh >/dev/null 2>&1 || return 0
  (cd "$REPO_ROOT" && gh pr view "$1" --json headRefOid --jq .headRefOid 2>/dev/null) || true
}

seed() {
  info "Seeding the owner (sign-up, TOTP and an agent key) and invented fixtures with that key"
  build_toolchain
  # The seed writes the owner's sign-in and the agent key to /state/owner.env (0600) and prints neither.
  TOOLCHAIN_EXTRA_ARGS=(--network "${PR_PROJECT}_default" -v "$STATE_DIR:/state"
    -e ADIUTOR_URL=http://adiutor:8080 -e "ADIUTOR_ORIGIN=$(pr_url)" -e ADIUTOR_OWNER_FILE=/state/owner.env)
  in_toolchain "node scripts/lib/try-pr-seed.mjs"
  TOOLCHAIN_EXTRA_ARGS=()
  [ -f "$OWNER_FILE" ] || die "the seed did not write $OWNER_FILE"
  chmod 600 "$OWNER_FILE"
}

try_pr() {
  local pr="$1" dev_port="${ADIUTOR_PORT:-8090}" expected
  [[ "$pr" =~ ^[1-9][0-9]*$ ]] || die "pull request number expected, got: $pr"
  if [ -f "$STATE_FILE" ]; then
    load_state
    die "pull request #$PR is running. Remove it first: scripts/try-pr.sh restore"
  fi
  PORT="${ADIUTOR_PR_PORT:-$DEFAULT_PORT}"
  if ! [[ "$PORT" =~ ^[1-9][0-9]{0,4}$ ]] || [ "$PORT" -gt 65535 ]; then
    die "ADIUTOR_PR_PORT must be a port number"
  fi
  [ "$PORT" != "$dev_port" ] || die "port $PORT belongs to the development stack; set ADIUTOR_PR_PORT to another port"
  require_linux_dir "$STATE_DIR"
  [ -z "$(docker ps -aq --filter "label=com.docker.compose.project=$PR_PROJECT")" ] ||
    die "containers of $PR_PROJECT exist without a record in $STATE_DIR. Remove them: scripts/try-pr.sh restore"
  if [ -e "$WORKTREE" ] || [ -e "$DATA_DIR" ]; then
    die "leftovers of an earlier pull request are in $STATE_DIR. Remove them: scripts/try-pr.sh restore"
  fi

  PR="$pr" COMMIT="" REF="refs/adiutor/try-pr/$pr" IMAGE="adiutor:pr-$pr"
  mkdir -p "$STATE_DIR"
  chmod 700 "$STATE_DIR"
  # Recorded before anything is created, so restore can always clean up.
  save_state

  info "Fetching pull request #$pr"
  git -C "$REPO_ROOT" fetch --quiet origin "+pull/$pr/head:$REF" ||
    die "cannot fetch pull request #$pr from origin. Clean up with: scripts/try-pr.sh restore"
  COMMIT="$(git -C "$REPO_ROOT" rev-parse "$REF")"
  expected="$(gh_head "$pr")"
  if [ -n "$expected" ] && [ "$expected" != "$COMMIT" ]; then
    die "GitHub reports head $expected for #$pr, but $COMMIT was fetched; it moved meanwhile. Run restore, then try again."
  fi
  save_state
  git -C "$REPO_ROOT" worktree add --quiet --detach "$WORKTREE" "$REF"

  info "Building $IMAGE from #$pr (${COMMIT:0:12})"
  docker build -f "$WORKTREE/docker/adiutor.Dockerfile" --build-arg "VERSION=pr$pr-${COMMIT:0:12}" -t "$IMAGE" "$WORKTREE" ||
    die "building $IMAGE failed. Clean up with: scripts/try-pr.sh restore"

  mkdir -p "$DATA_DIR"
  write_env
  ensure_auth_secret
  write_compose
  write_proxy_conf
  info "Starting $PR_PROJECT on $(pr_url)"
  pr_compose up -d --wait --wait-timeout 120 || {
    pr_compose ps -a || true
    pr_compose logs --tail 50 || true
    die "the pull request stack did not become healthy. Clean up with: scripts/try-pr.sh restore"
  }
  check_non_root "$PR_PROJECT" adiutor postgres proxy
  check_hardening "$PR_PROJECT" adiutor proxy
  seed || die "seeding failed; the stack still runs. Inspect it, then: scripts/try-pr.sh restore"

  info "Pull request #$pr (${COMMIT:0:12}) runs on $(pr_url)"
  echo "    sign in with: $OWNER_FILE (username, password, TOTP secret, backup codes)"
  echo "    agent key for API calls: $OWNER_FILE (ADIUTOR_AGENT_KEY)"
  echo "    when done: scripts/try-pr.sh restore"
}

status() {
  if [ ! -f "$STATE_FILE" ]; then
    info "No pull request is running"
    return 0
  fi
  load_state
  local url=""
  [ -f "$ENV_FILE" ] && url="$(sed -n 's/^ADIUTOR_PUBLIC_URL=//p' "$ENV_FILE")"
  if [ -z "$url" ]; then
    info "Pull request #$PR: its setup did not finish. Remove it: scripts/try-pr.sh restore"
  else
    info "Pull request #$PR (${COMMIT:0:12}) as $PR_PROJECT on $url"
    if [ "$url" != "$(pr_url)" ] || { [ -f "$COMPOSE_FILE" ] && ! grep -q '^  proxy:' "$COMPOSE_FILE"; }; then
      echo "    started by an older try-pr.sh; to serve it on $(pr_url): scripts/try-pr.sh restore, then run it again"
    fi
  fi
  echo "    worktree: $WORKTREE"
  echo "    keys:     $ENV_FILE"
  echo "    sign-in:  $OWNER_FILE"
  ensure_auth_secret
  [ -f "$COMPOSE_FILE" ] || {
    echo "    the stack was not started"
    return 0
  }
  pr_compose ps
  local cid health
  cid="$(pr_compose ps -q adiutor)"
  [ -n "$cid" ] || die "service adiutor is not running"
  health="$(docker inspect -f '{{.State.Health.Status}}' "$cid")"
  echo "    adiutor health: $health"
  [ "$(docker inspect -f '{{.Config.Image}}' "$cid")" = "$IMAGE" ] || die "adiutor does not run $IMAGE"
  if grep -q '^  proxy:' "$COMPOSE_FILE"; then
    check_non_root "$PR_PROJECT" adiutor postgres proxy
    check_hardening "$PR_PROJECT" adiutor proxy
    cid="$(pr_compose ps -q proxy)"
    [ -n "$cid" ] || die "service proxy is not running"
    [ "$(docker inspect -f '{{.State.Health.Status}}' "$cid")" = healthy ] || die "proxy is not healthy"
  else
    check_non_root "$PR_PROJECT" adiutor postgres
    check_hardening "$PR_PROJECT"
  fi
  [ "$health" = healthy ] || die "adiutor is not healthy"
}

restore() {
  if [ -f "$STATE_FILE" ]; then
    load_state
    info "Removing pull request #$PR"
  else
    info "No pull request is recorded; removing any leftovers"
  fi
  require_linux_dir "$STATE_DIR"
  # Only this project's containers and network; the development stack is a different project.
  if [ -f "$COMPOSE_FILE" ]; then
    pr_compose down --remove-orphans
  elif [ -n "$(docker ps -aq --filter "label=com.docker.compose.project=$PR_PROJECT")" ]; then
    docker compose -p "$PR_PROJECT" down --remove-orphans
  fi
  [ -z "$(docker ps -aq --filter "label=com.docker.compose.project=$PR_PROJECT")" ] ||
    die "containers of $PR_PROJECT still exist"
  remove_data_dir "$DATA_DIR"
  if [ -n "$IMAGE" ] && docker image inspect "$IMAGE" >/dev/null 2>&1; then
    docker rmi "$IMAGE" >/dev/null
  fi
  if [ -e "$WORKTREE" ]; then
    git -C "$REPO_ROOT" worktree remove --force "$WORKTREE" 2>/dev/null || rm -rf "$WORKTREE"
  fi
  git -C "$REPO_ROOT" worktree prune
  if [ -n "$REF" ] && git -C "$REPO_ROOT" rev-parse -q --verify "$REF" >/dev/null; then
    git -C "$REPO_ROOT" update-ref -d "$REF"
  fi
  rm -f "$ENV_FILE" "$OWNER_FILE" "$COMPOSE_FILE" "$PROXY_CONF" "$STATE_FILE"
  rmdir "$STATE_DIR" 2>/dev/null || true
  if [ -n "$PR" ]; then
    info "Removed pull request #$PR: stack, database, image, tokens, sign-in and worktree"
  else
    info "Nothing of a pull request stack is left"
  fi
}

main() {
  case "${1:-}" in
    -h | --help | help | "")
      usage
      return 0
      ;;
  esac
  [ $# -eq 1 ] || {
    usage
    die "one command expected"
  }
  require_docker
  case "$1" in
    status) status ;;
    restore) restore ;;
    *) try_pr "$1" ;;
  esac
}

# scripts/test-try-pr.sh sources this file for its functions.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
